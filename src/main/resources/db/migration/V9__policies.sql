create table policies (
                          id bigint generated by default as identity primary key,
                          policy_number varchar(100) not null unique,
                          client_id bigint not null,
                          building_id bigint not null,
                          broker_id bigint not null,
                          currency_id bigint not null,
                          status varchar(20) not null,
                          start_date date not null,
                          end_date date not null,
                          base_premium decimal(19,6) not null,
                          final_premium decimal(19,6) not null,
                          cancellation_reason varchar(500),
                          created_at timestamp default current_timestamp,
                          updated_at timestamp
);

alter table policies
    add constraint fk_policy_client foreign key (client_id) references clients(id);

alter table policies
    add constraint fk_policy_building foreign key (building_id) references buildings(id);

alter table policies
    add constraint fk_policy_broker foreign key (broker_id) references brokers(id);

alter table policies
    add constraint fk_policy_currency foreign key (currency_id) references currencies(id);
