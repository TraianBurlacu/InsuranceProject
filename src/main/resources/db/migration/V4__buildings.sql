create table buildings (
                           id bigint generated by default as identity primary key,

                           client_id bigint not null,
                           city_id bigint not null,

                           street varchar(200) not null,
                           number varchar(20) not null,

                           construction_year int,
                           building_type varchar(30) not null,
                           floors int,
                           surface_area decimal(12,2) not null,
                           insured_value decimal(14,2) not null,

                           risk_indicators varchar(500),

                           constraint fk_buildings_client foreign key (client_id) references clients(id),
                           constraint fk_buildings_city foreign key (city_id) references cities(id)
);

create index idx_buildings_client_id on buildings(client_id);
create index idx_buildings_city_id on buildings(city_id);
